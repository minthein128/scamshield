import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { BENCH_DIR, type BenchResult, resultsDir } from './lib.js';

interface TextEval {
  kind: 'text-eval';
  date: string;
  model: string;
  cases: number;
  correct: number;
  p50: number;
  p95: number;
  rows: { id: string; lang: string; expect: string; verdict: string; ok: boolean }[];
}

const pct = (x: number | null) => (x === null ? 'n/a' : `${(100 * x).toFixed(1)}%`);
const table = (head: string[], rows: (string | number)[][]) =>
  [`| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');
const sec = (ms: number) => `${(ms / 1000).toFixed(1)} s`;

function load() {
  const shots: (BenchResult & { file: string })[] = [];
  const texts: (TextEval & { file: string })[] = [];
  for (const file of readdirSync(resultsDir())
    .filter((f) => f.endsWith('.json'))
    .sort()) {
    const doc = JSON.parse(readFileSync(join(resultsDir(), file), 'utf8'));
    if (doc.kind === 'screenshot-bench') shots.push({ ...doc, file });
    else if (doc.kind === 'text-eval') texts.push({ ...doc, file });
  }
  return { shots, texts };
}

const byDate = <T extends { date: string; file: string }>(xs: T[]) =>
  [...xs].sort((a, b) => (a.date + a.file).localeCompare(b.date + b.file));

export function writeReport() {
  const { shots, texts } = load();
  const out: string[] = [
    '# Benchmark results',
    '',
    'Generated by `npm run bench:report` from the JSON files in `bench/results/`. Do not edit by hand.',
    '',
  ];

  out.push('## Screenshot bench, latest run per set', '');
  const sets = [...new Set(shots.map((s) => s.set))].sort();
  if (!sets.length) out.push('No runs yet.', '');
  for (const set of sets) {
    const r = byDate(shots.filter((s) => s.set === set)).at(-1) as BenchResult & { file: string };
    const s = r.summary;
    out.push(
      `### ${set}: ${r.date}, ${r.model}, ${s.n} screenshots`,
      '',
      table(
        ['Metric', 'Value'],
        [
          ['Accuracy (risky = careful or danger)', `${pct(s.accuracy)} (${Math.round(s.accuracy * s.n)}/${s.n})`],
          ['Exact verdict accuracy (3 classes)', pct(s.exactAccuracy)],
          ['False-positive rate on safe cases', `${pct(s.falsePositiveRate)} (${s.safeCases} safe)`],
          ['Missed-scam rate on risky cases', `${pct(s.missRate)} (${s.riskyCases} risky)`],
          ['Scam type accuracy on risky cases', pct(s.scamTypeAccuracy)],
          ['Latency p50 / p95', `${sec(s.p50)} / ${sec(s.p95)}`],
          [
            'PII patterns surviving in model text',
            `${s.piiLeaks}${
              s.piiLeaks
                ? ` (${Object.entries(s.piiByType)
                    .map(([k, v]) => `${k} ${v}`)
                    .join(', ')})`
                : ''
            }`,
          ],
          [
            'Responses with certainty wording (before / after guard)',
            s.certainty ? `${s.certainty.before ?? 'n/a'} / ${s.certainty.after} of ${s.certainty.measured}` : 'not measured',
          ],
          ['Request errors', s.errors],
        ],
      ),
      '',
      'Confusion matrix (rows expected, columns predicted):',
      '',
      table(
        ['expected', 'safe', 'careful', 'danger', 'error'],
        Object.entries(s.confusion).map(([k, v]) => [k, v.safe ?? 0, v.careful ?? 0, v.danger ?? 0, v.ERROR ?? 0]),
      ),
      '',
      table(
        ['App', 'Correct', 'Accuracy'],
        Object.entries(s.perApp)
          .sort()
          .map(([k, v]) => [k, `${v.correct}/${v.n}`, pct(v.correct / v.n)]),
      ),
      '',
      table(
        ['Language', 'Correct', 'Accuracy'],
        Object.entries(s.perLanguage)
          .sort()
          .map(([k, v]) => [k, `${v.correct}/${v.n}`, pct(v.correct / v.n)]),
      ),
      '',
    );
  }

  out.push('## Text eval, latest run', '');
  const t = byDate(texts).at(-1);
  if (t) {
    out.push(`${t.date}, ${t.model}, ${t.correct}/${t.cases} correct, p50 ${sec(t.p50)}, p95 ${sec(t.p95)}.`, '');
    const langs: Record<string, { n: number; ok: number }> = {};
    for (const r of t.rows) {
      const b = langs[r.lang] ?? { n: 0, ok: 0 };
      b.n++;
      if (r.ok) b.ok++;
      langs[r.lang] = b;
    }
    out.push(
      table(
        ['Language', 'Correct'],
        Object.entries(langs)
          .sort()
          .map(([k, v]) => [k, `${v.ok}/${v.n}`]),
      ),
      '',
    );
  } else out.push('No runs yet.', '');

  out.push('## History', '');
  const hist = [
    ...byDate(shots).map((r) => [
      r.date,
      'screenshots',
      r.set,
      r.model,
      r.summary.n,
      pct(r.summary.accuracy),
      pct(r.summary.falsePositiveRate),
      sec(r.summary.p50),
      sec(r.summary.p95),
      r.summary.piiLeaks,
    ]),
    ...byDate(texts).map((r) => [r.date, 'text', '27 cases', r.model, r.cases, pct(r.correct / r.cases), '-', sec(r.p50), sec(r.p95), '-']),
  ].sort((a, b) => String(b[0]).localeCompare(String(a[0])));
  out.push(table(['Date', 'Bench', 'Set', 'Model', 'N', 'Accuracy', 'False positives', 'p50', 'p95', 'PII leaks'], hist), '');
  writeFileSync(join(BENCH_DIR, 'RESULTS.md'), `${out.join('\n')}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeReport();
  console.log('wrote bench/RESULTS.md');
}
