import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { HOTLINES } = await import(`${root}/src/data/hotlines.ts`);
const { COUNTRIES } = await import(`${root}/src/data/countries.ts`);

const out = `// Generated by scripts/sync-hotlines.mjs from src/data. Do not edit.
export type HotlineCategory = 'trafficking' | 'police' | 'cybercrime' | 'consular' | 'ngo';

export interface Hotline {
  id: string;
  country: string;
  category: HotlineCategory;
  name: string;
  number?: string;
  dial?: string;
  domesticOnly?: boolean;
  reportUrl?: string;
  hours?: string;
  notes?: string;
  sourceUrl: string;
  asOf?: string;
  verifiedOn: string;
}

export interface Country {
  code: string;
  name: string;
  aliases: string[];
}

export const COUNTRIES: Country[] = ${JSON.stringify(COUNTRIES, null, 2)};

export const HOTLINES: Hotline[] = ${JSON.stringify(HOTLINES, null, 2)};
`;
const target = `${root}/server/src/data/hotlines.generated.ts`;
if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== out) {
    console.error('server/src/data/hotlines.generated.ts is out of date. Run: pnpm sync:hotlines');
    process.exit(1);
  }
  console.log(`server hotline data matches src/data (${HOTLINES.length} hotlines)`);
} else {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, out);
  console.log(`wrote ${target} (${HOTLINES.length} hotlines)`);
}
